import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const adminDir = path.join(root, "admin");
const envPath = path.join(adminDir, ".env");
const examplePath = path.join(adminDir, ".env.example");
const outPath = path.join(adminDir, "config.js");

const KEYS = [
  "SUPABASE_URL",
  "SUPABASE_ANON_KEY",
  "SITE_BASE_URL",
  "NEWS_SYNC_SECRET",
];

const DEFAULTS = {
  SITE_BASE_URL: "http://localhost:8000/",
  NEWS_SYNC_SECRET: "",
};

const parseEnv = (content) => {
  const vars = {};
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const eq = trimmed.indexOf("=");
    if (eq === -1) {
      continue;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
};

const loadValues = async () => {
  const fileVars = existsSync(envPath) ? parseEnv(await readFile(envPath, "utf8")) : {};
  const values = {};
  for (const key of KEYS) {
    values[key] = process.env[key] ?? fileVars[key] ?? DEFAULTS[key] ?? "";
  }
  return values;
};

const buildConfigSource = (values) => {
  const lines = [
    "// Generated by scripts/generate-admin-config.mjs — do not edit by hand.",
    "// Set values in admin/.env (see admin/.env.example), then run: npm run admin:config",
    "",
  ];
  for (const key of KEYS) {
    lines.push(`export const ${key} = ${JSON.stringify(values[key] ?? "")};`);
  }
  lines.push("");
  return lines.join("\n");
};

const main = async () => {
  if (!existsSync(envPath) && !process.env.SUPABASE_URL) {
    console.error(
      "Missing admin/.env and no SUPABASE_URL in the environment.\n" +
        `Copy ${path.relative(root, examplePath)} to admin/.env and fill in your values.`
    );
    process.exit(1);
  }

  const values = await loadValues();
  if (!values.SUPABASE_URL || !values.SUPABASE_ANON_KEY) {
    console.error("SUPABASE_URL and SUPABASE_ANON_KEY are required in admin/.env or env vars.");
    process.exit(1);
  }

  await writeFile(outPath, buildConfigSource(values), "utf8");
  console.log(`Wrote ${path.relative(root, outPath)} from admin/.env`);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
